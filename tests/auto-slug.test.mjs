import test from 'node:test';
import assert from 'node:assert/strict';
import { bindAutoSlug, slugFromTitle } from '../resources/js/lontar/auto-slug.js';

class Field extends EventTarget {
  constructor(value = '') { super(); this.value = value; this.dataset = {}; this.readOnly = false; }
  type(value) { this.value = value; this.dispatchEvent(new Event('input')); }
}

function setup({ value = '', titleValue = '', id = '', readOnly = false, fetcher } = {}) {
  const title = new Field(titleValue);
  const input = new Field(value);
  input.dataset = { autoSlug: 'exams', slugUrl: 'https://slug.test/admin/slugs/preview', slugId: id };
  input.readOnly = readOnly;
  const status = {};
  const tasks = new Map();
  const requests = [];
  let token = 0;
  bindAutoSlug(input, title, { status,
    schedule: callback => { tasks.set(++token, callback); return token; },
    cancel: key => tasks.delete(key),
    fetcher: async (url, options) => {
      requests.push({ url: new URL(url), options });
      return fetcher ? fetcher(url, options) : { ok: true, json: async () => ({ slug: 'judul-sama-2' }) };
    },
  });
  const flush = async () => { const pending = [...tasks.values()]; tasks.clear(); await Promise.all(pending.map(callback => callback())); };
  return { title, input, status, requests, flush, tasks };
}

test('title conversion handles punctuation, diacritics, length limits and blank input', () => {
  assert.equal(slugFromTitle('  Latihan TWK & TIU!  ', 'exams'), 'latihan-twk-and-tiu');
  assert.equal(slugFromTitle('Café Déjà Vu', 'articles'), 'cafe-deja-vu');
  assert.equal(slugFromTitle('😀', 'sections'), 'bidang');
  assert.equal(slugFromTitle('   ', 'materials'), '');
  assert.equal(slugFromTitle('A'.repeat(180), 'exams').length, 80);
});

test('slug follows the title immediately then adopts the available server slug without repeated requests', async () => {
  const view = setup();
  view.title.type('Judul Sama');
  assert.equal(view.input.value, 'judul-sama');
  await view.flush();
  assert.equal(view.input.value, 'judul-sama-2');
  assert.equal(view.requests.length, 1);
  assert.equal(view.requests[0].url.searchParams.get('value'), 'Judul Sama');
  assert.equal(view.requests[0].url.searchParams.get('resource'), 'exams');
  assert.match(view.status.textContent, /Alamat tersedia/);
  assert.equal(view.tasks.size, 0);
});

test('rapid typing only checks the latest title and clearing the title cancels a pending check', async () => {
  const view = setup();
  view.title.type('Judul');
  view.title.type('Judul Sama');
  await view.flush();
  assert.equal(view.requests.length, 1);
  assert.equal(view.requests[0].url.searchParams.get('value'), 'Judul Sama');
  view.title.type('Judul Baru');
  view.title.type('');
  await view.flush();
  assert.equal(view.requests.length, 1);
  assert.equal(view.input.value, '');
});

test('manual addresses survive title changes and clearing an address restores automatic filling', async () => {
  const view = setup();
  view.title.type('Judul Awal');
  view.input.type('alamat-khusus');
  view.title.type('Judul Diganti');
  assert.equal(view.input.value, 'alamat-khusus');
  await view.flush();
  assert.equal(view.requests[0].url.searchParams.get('value'), 'alamat-khusus');
  view.input.type('');
  assert.equal(view.input.value, 'judul-diganti');
});

test('existing addresses stay fixed on title edits and manual checks ignore the current record', async () => {
  const view = setup({ value: 'alamat-tetap', id: '42' });
  view.title.type('Judul Diganti');
  await view.flush();
  assert.equal(view.input.value, 'alamat-tetap');
  assert.equal(view.requests.length, 0);
  view.input.type('alamat-kustom');
  await view.flush();
  assert.equal(view.requests[0].url.searchParams.get('ignore_id'), '42');
});

test('locked session addresses cannot be regenerated by title changes', async () => {
  const view = setup({ value: 'alamat-tetap', readOnly: true });
  view.title.type('Judul Diganti');
  await view.flush();
  assert.equal(view.input.value, 'alamat-tetap');
  assert.equal(view.requests.length, 0);
});

test('late responses cannot overwrite the newest title or a custom address', async () => {
  let resolveOld;
  let calls = 0;
  const view = setup({ fetcher: async () => {
    calls++;
    if (calls === 1) return new Promise(resolve => { resolveOld = resolve; });
    return { ok: true, json: async () => ({ slug: 'judul-baru-2' }) };
  } });
  view.title.type('Judul Lama');
  const old = view.flush();
  view.title.type('Judul Baru');
  await view.flush();
  resolveOld({ ok: true, json: async () => ({ slug: 'judul-lama-2' }) });
  await old;
  assert.equal(view.input.value, 'judul-baru-2');
  assert.equal(view.requests[0].options.signal.aborted, true);
});

test('failed previews keep the generated address available for server validation at save', async () => {
  const view = setup({ fetcher: async () => ({ ok: false }) });
  view.title.type('Judul Sama');
  await view.flush();
  assert.equal(view.input.value, 'judul-sama');
  assert.match(view.status.textContent, /saat disimpan/);
});
